CREATE TABLE book_publications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    egov_id varchar(30),
    staff_id bigint NOT NULL,
    title varchar(255) NOT NULL,
    book_level text NOT NULL,
    publisher_name varchar(255) NOT NULL,
    edition varchar(255) NOT NULL,
    doi varchar(255) NOT NULL,
    date date NOT NULL,
    issue varchar(255),
    type text NOT NULL,
    chapter_title varchar(255),
    start_page_no integer,
    end_page_no integer,
    validation_status text NOT NULL DEFAULT 'new',
    reason varchar(255),
    document varchar(255) NOT NULL,
    created_at timestamp,
    updated_at timestamp,
    CHECK (book_level IN ('National','International')),
    CHECK (type IN ('Book','Chapter')),
    CHECK (validation_status IN ('new','valid','invalid','updated'))
);
