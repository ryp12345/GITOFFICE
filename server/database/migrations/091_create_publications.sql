CREATE TABLE publications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    egov_id varchar(30) NOT NULL,
    staff_id bigint NOT NULL,
    level text NOT NULL,
    other_level varchar(255),
    title varchar(255) NOT NULL,
    date date NOT NULL,
    journal varchar(255) NOT NULL,
    doi_number varchar(255),
    link varchar(255),
    role varchar(255) NOT NULL,
    volume varchar(255),
    issue varchar(255),
    page_no varchar(255),
    year varchar(255) NOT NULL,
    publication_type text NOT NULL,
    validation_status text NOT NULL DEFAULT 'new',
    reason varchar(255),
    document varchar(255) NOT NULL,
    created_at timestamp,
    updated_at timestamp,
    CHECK (level IN ('Q1','Q2','Q3','Q4','Web of Science','SCI','Scopus Indexed','UGC General','Other')),
    CHECK (publication_type IN ('Journal','Conference Proceeding')),
    CHECK (validation_status IN ('new','valid','invalid','updated'))
);
